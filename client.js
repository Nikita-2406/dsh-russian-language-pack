    function messageOf(error) {
      return error && error.message ? String(error.message) : String(error);
    }
    function registerDictionaries(locale) {
      const disposers = [];
      for (const ns of Object.keys(DICTS)) {
        try {
          disposers.push(locale.register(ns, LOCALE_ID, DICTS[ns]));
        } catch (error) {
          if (!/already has locale/.test(messageOf(error))) throw error;
        }
      }
      return disposers;
    }
    function addLanguageDefinition(locale) {
      const already = locale.getLocale().locales.some((entry) => String(entry.id).toLowerCase() === LOCALE_ID);
      if (already) return null;
      try {
        return locale.addLanguage({ id: LOCALE_ID, label: 'Русский', fallback: 'en' });
      } catch (error) {
        if (!/is already registered/.test(messageOf(error))) throw error;
        return null;
      }
    }
    function autoSelect(ctx, locale) {
      let scope = null;
      try {
        const configForms = ctx.get('configForms');
        scope = configForms ? configForms.get('locale') : null;
      } catch (error) {
        scope = null;
      }
      if (!scope || typeof scope.getSnapshot !== 'function') return;
      let decided = false;
      const decide = () => {
        if (decided) return;
        const snapshot = scope.getSnapshot();
        const section = snapshot ? snapshot.value : undefined;
        if (section === undefined || section === null || typeof section !== 'object') return;
        decided = true;
        if (section.preference) return;
        if (locale.getLocale().active !== LOCALE_ID) {
          try {
            locale.setLocale(LOCALE_ID);
          } catch (error) {
            console.error('[russian-language-pack] setLocale failed:', error);
          }
        }
      };
      ctx.effect(() => {
        let unsubscribe = null;
        try {
          unsubscribe = scope.subscribe(decide);
        } catch (error) {
          unsubscribe = null;
        }
        decide();
        return () => {
          if (typeof unsubscribe === 'function') unsubscribe();
        };
      }, 'russian-language-pack: locale auto-select');
    }
    return {
      inject: ['locale'],
      apply(ctx) {
        const locale = ctx.locale || ctx.get('locale');
        if (!locale) return;
        const disposers = [];
        const language = addLanguageDefinition(locale);
        if (language) disposers.push(language);
        for (const dispose of registerDictionaries(locale)) disposers.push(dispose);
        ctx.effect(() => () => {
          for (const dispose of disposers) {
            try {
              dispose();
            } catch (error) {
              // best effort: the plugin is being torn down anyway
            }
          }
        }, 'russian-language-pack: dictionaries');
        autoSelect(ctx, locale);
      },
    };
